//! Generates parts of the Zig port from the Rust CLI parser sources.
//!
//! - `help [COMMAND]`: print help as rendered by the Rust parser
//! - `goldens DIR`: write the root and every subcommand's help into DIR
//! - `zig-defs`: print `zig/src/cli/defs.zig`
//! - `zig-env-vars`: print `zig/src/cli/env_vars.zig`
//! - `extract-argv FILE...`: print every `svec![...]` argv in the given Rust
//!   test files as JSON lines (a parser test corpus)
//! - `parse-corpus FILE`: parse each JSON-lines argv in FILE with the Rust
//!   parser and print the results in the format of `zig/src/cli/parse.zig`

#![allow(dead_code)]

#[path = "../../../../libs/cli_parser/src/defs.rs"]
mod defs;
#[path = "../../../../libs/cli_parser/src/env_vars.rs"]
mod env_vars;
#[path = "../../../../libs/cli_parser/src/error.rs"]
mod error;
#[path = "../../../../libs/cli_parser/src/help.rs"]
mod help;
#[path = "../../../../libs/cli_parser/src/parse.rs"]
mod parse;
#[path = "../../../../libs/cli_parser/src/permission_help.rs"]
mod permission_help;
#[path = "../../../../libs/cli_parser/src/types.rs"]
mod types;

use std::fmt::Write;

pub use types::*;

fn main() {
  let args: Vec<String> = std::env::args().skip(1).collect();
  let root = &defs::DENO_ROOT;
  match args
    .iter()
    .map(String::as_str)
    .collect::<Vec<_>>()
    .as_slice()
  {
    ["help"] => print!("{}", help::render_help(root)),
    ["help", name] => match help::render_subcommand_help(root, name) {
      Some(text) => print!("{text}"),
      None => {
        eprintln!("unknown command: {name}");
        std::process::exit(1);
      }
    },
    ["goldens", dir] => {
      let dir = std::path::Path::new(dir);
      std::fs::write(dir.join("root.txt"), help::render_help(root)).unwrap();
      for sub in root.subcommands {
        if sub.name.starts_with("json_reference") {
          continue;
        }
        std::fs::write(
          dir.join(format!("{}.txt", sub.name)),
          help::render_help(sub),
        )
        .unwrap();
      }
    }
    ["zig-defs"] => print!("{}", zig_defs()),
    ["zig-env-vars"] => print!("{}", zig_env_vars()),
    ["extract-argv", files @ ..] => {
      let mut seen = std::collections::HashSet::new();
      for file in files {
        let src = std::fs::read_to_string(file).unwrap();
        for argv in extract_argv(&src) {
          let line = serde_json::to_string(&argv).unwrap();
          if seen.insert(line.clone()) {
            println!("{line}");
          }
        }
      }
    }
    ["parse-corpus", file] => {
      let src = std::fs::read_to_string(file).unwrap();
      for line in src.lines().filter(|l| !l.is_empty()) {
        let argv: Vec<String> = serde_json::from_str(line).unwrap();
        print!("{}", render_parse(&argv));
      }
    }
    _ => {
      eprintln!(
        "usage: zig_cli_reference help [COMMAND] | goldens DIR | zig-defs | zig-env-vars | extract-argv FILE... | parse-corpus FILE"
      );
      std::process::exit(2);
    }
  }
}

const HEADER: &str = "// Copyright 2018-2026 the Deno authors. MIT license.\n\
  // Generated by zig/tools/regen_cli.sh. DO NOT EDIT.\n";

/// The shared argument groups, by name. Commands reference these by pointer,
/// which lets `help` detect e.g. the permission args.
fn named_groups() -> Vec<(&'static str, &'static [ArgDef])> {
  vec![
    ("permission_args", defs::PERMISSION_ARGS),
    ("compile_args", defs::COMPILE_ARGS),
    ("inspect_args", defs::INSPECT_ARGS),
    ("runtime_misc_args", defs::RUNTIME_MISC_ARGS),
    ("cpu_prof_args", defs::CPU_PROF_ARGS),
    ("unstable_deprecated_arg", defs::UNSTABLE_DEPRECATED_ARG),
    ("unstable_feature_args", defs::UNSTABLE_FEATURE_ARGS),
    ("import_permission_args", defs::IMPORT_PERMISSION_ARGS),
    ("allow_scripts_arg", defs::ALLOW_SCRIPTS_ARG),
    ("lock_args", defs::LOCK_ARGS),
    ("global_args", defs::GLOBAL_ARGS),
  ]
}

fn group_name(group: &'static [ArgDef]) -> &'static str {
  named_groups()
    .into_iter()
    .find(|(_, g)| std::ptr::eq(g.as_ptr(), group.as_ptr()))
    .map(|(name, _)| name)
    .unwrap_or_else(|| {
      panic!("unnamed arg group starting with {:?}", group[0].name)
    })
}

fn tag(name: &str) -> String {
  let ident = name.replace('-', "_");
  // Zig keywords need quoting.
  if matches!(ident.as_str(), "test" | "and" | "or" | "error" | "type") {
    format!("@\"{ident}\"")
  } else {
    ident
  }
}

fn zig_str(s: &str) -> String {
  let mut out = String::from("\"");
  for c in s.chars() {
    match c {
      '\\' => out.push_str("\\\\"),
      '"' => out.push_str("\\\""),
      '\n' => out.push_str("\\n"),
      '\t' => out.push_str("\\t"),
      '\r' => out.push_str("\\r"),
      c if (c as u32) < 0x20 => write!(out, "\\x{:02x}", c as u32).unwrap(),
      c => out.push(c),
    }
  }
  out.push('"');
  out
}

fn zig_opt_str(s: Option<&str>) -> Option<String> {
  s.map(zig_str)
}

fn zig_str_list(list: &[&str]) -> String {
  let items: Vec<String> = list.iter().map(|s| zig_str(s)).collect();
  format!("&.{{ {} }}", items.join(", "))
}

fn zig_char(c: char) -> String {
  assert!(c.is_ascii(), "non-ASCII short flag {c:?}");
  format!("'{c}'")
}

fn zig_arg(a: &ArgDef, indent: &str) -> String {
  let mut fields = vec![format!(".name = {}", zig_str(a.name))];
  let mut push = |s: String| fields.push(s);
  if let Some(c) = a.short {
    push(format!(".short = {}", zig_char(c)));
  }
  if let Some(l) = a.long {
    push(format!(".long = {}", zig_str(l)));
  }
  if !a.short_aliases.is_empty() {
    let items: Vec<String> =
      a.short_aliases.iter().map(|c| zig_char(*c)).collect();
    push(format!(".short_aliases = &.{{ {} }}", items.join(", ")));
  }
  if !a.long_aliases.is_empty() {
    push(format!(".long_aliases = {}", zig_str_list(a.long_aliases)));
  }
  if !a.help.is_empty() {
    push(format!(".help = {}", zig_str(a.help)));
  }
  let action = match a.action {
    ArgAction::SetTrue => "set_true",
    ArgAction::Set => "set",
    ArgAction::Append => "append",
    ArgAction::Count => "count",
  };
  if action != "set" {
    push(format!(".action = .{action}"));
  }
  match a.num_args {
    NumArgs::Exact(1) => {}
    NumArgs::Exact(n) => push(format!(".num_args = .{{ .exact = {n} }}")),
    NumArgs::Optional => push(".num_args = .optional".into()),
    NumArgs::ZeroOrMore => push(".num_args = .zero_or_more".into()),
    NumArgs::OneOrMore => push(".num_args = .one_or_more".into()),
  }
  if let Some(d) = a.value_delimiter {
    push(format!(".value_delimiter = {}", zig_char(d)));
  }
  for (set, name) in [
    (a.require_equals, "require_equals"),
    (a.required, "required"),
    (a.global, "global"),
    (a.hidden, "hidden"),
    (a.positional, "positional"),
    (a.trailing, "trailing"),
  ] {
    if set {
      push(format!(".{name} = true"));
    }
  }
  if let Some(v) = zig_opt_str(a.default_value) {
    push(format!(".default_value = {v}"));
  }
  if let Some(v) = zig_opt_str(a.value_name) {
    push(format!(".value_name = {v}"));
  }
  if !a.conflicts.is_empty() {
    push(format!(".conflicts = {}", zig_str_list(a.conflicts)));
  }
  if !a.requires.is_empty() {
    push(format!(".requires = {}", zig_str_list(a.requires)));
  }
  if let Some(p) = a.value_parser {
    let v = match p {
      ValueParser::Choices(c) => {
        format!(".{{ .choices = {} }}", zig_str_list(c))
      }
      ValueParser::Bool => ".bool".into(),
      ValueParser::U8 => ".u8".into(),
      ValueParser::U16 => ".u16".into(),
      ValueParser::U32 => ".u32".into(),
      ValueParser::U64 => ".u64".into(),
      ValueParser::Usize => ".usize".into(),
      ValueParser::NonZeroU8 => ".non_zero_u8".into(),
      ValueParser::NonZeroU32 => ".non_zero_u32".into(),
      ValueParser::NonZeroUsize => ".non_zero_usize".into(),
      ValueParser::U32Range(lo, hi) => {
        format!(".{{ .u32_range = .{{ .lo = {lo}, .hi = {hi} }} }}")
      }
    };
    push(format!(".value_parser = {v}"));
  }
  let inner = format!("{indent}    ");
  format!(
    "{indent}.{{\n{}{indent}}},\n",
    fields
      .iter()
      .map(|f| format!("{inner}{f},\n"))
      .collect::<String>()
  )
}

fn zig_args(args: &[ArgDef], indent: &str) -> String {
  if args.is_empty() {
    return "&.{}".into();
  }
  let items: String = args
    .iter()
    .map(|a| zig_arg(a, &format!("{indent}    ")))
    .collect();
  format!("&.{{\n{items}{indent}}}")
}

fn zig_command(cmd: &CommandDef, tag_name: Option<&str>) -> String {
  let mut out = String::from(".{\n");
  if let Some(t) = tag_name {
    writeln!(out, "    .tag = .{t},").unwrap();
  }
  writeln!(out, "    .name = {},", zig_str(cmd.name)).unwrap();
  writeln!(out, "    .about = {},", zig_str(cmd.about)).unwrap();
  if !cmd.aliases.is_empty() {
    writeln!(out, "    .aliases = {},", zig_str_list(cmd.aliases)).unwrap();
  }
  writeln!(out, "    .args = {},", zig_args(cmd.args, "    ")).unwrap();
  if !cmd.arg_groups.is_empty() {
    let groups: Vec<&str> =
      cmd.arg_groups.iter().map(|g| group_name(g)).collect();
    writeln!(out, "    .arg_groups = &.{{ {} }},", groups.join(", ")).unwrap();
  }
  if let Some(d) = cmd.default_subcommand {
    writeln!(out, "    .default_subcommand = {},", zig_str(d)).unwrap();
  }
  for (set, name) in [
    (cmd.trailing_var_arg, "trailing_var_arg"),
    (cmd.passthrough, "passthrough"),
    (cmd.keep_double_dash, "keep_double_dash"),
  ] {
    if set {
      writeln!(out, "    .{name} = true,").unwrap();
    }
  }
  out.push('}');
  out
}

fn zig_defs() -> String {
  let root = &defs::DENO_ROOT;
  let mut out = String::from(HEADER);
  out.push_str(
    "//! The Deno command tree, generated from `libs/cli_parser/src/defs.rs`.\n\n\
     const types = @import(\"types.zig\");\n\
     const Arg = types.Arg;\n\
     const CommandDef = types.CommandDef;\n\n",
  );

  out.push_str("/// One tag per top-level subcommand, in definition order.\npub const Tag = enum {\n");
  for sub in root.subcommands {
    writeln!(out, "    {},", tag(sub.name)).unwrap();
  }
  out.push_str("};\n\n");

  for (name, group) in named_groups() {
    writeln!(
      out,
      "pub const {name}: []const Arg = {};\n",
      zig_args(group, "")
    )
    .unwrap();
  }

  out.push_str("pub const subcommands = [_]CommandDef{\n");
  for sub in root.subcommands {
    let body = zig_command(sub, Some(&tag(sub.name)));
    for line in body.lines() {
      writeln!(out, "    {line}").unwrap();
    }
    out.pop();
    out.push_str(",\n");
  }
  out.push_str("};\n\n");

  assert!(std::ptr::eq(root.args.as_ptr(), defs::GLOBAL_ARGS.as_ptr()));
  out.push_str(
    "/// The `deno` root command.\npub const root: CommandDef = .{\n",
  );
  writeln!(out, "    .name = {},", zig_str(root.name)).unwrap();
  writeln!(out, "    .about = {},", zig_str(root.about)).unwrap();
  out.push_str("    .args = global_args,\n");
  let groups: Vec<&str> =
    root.arg_groups.iter().map(|g| group_name(g)).collect();
  writeln!(out, "    .arg_groups = &.{{ {} }},", groups.join(", ")).unwrap();
  out.push_str("    .subcommands = &subcommands,\n");
  writeln!(
    out,
    "    .default_subcommand = {},",
    zig_str(root.default_subcommand.unwrap())
  )
  .unwrap();
  out.push_str("};\n\n");

  out.push_str("/// The \"Permission options\" section of help for commands that accept\n/// `permission_args`.\n");
  writeln!(
    out,
    "pub const permission_help = {};",
    zig_str(permission_help::PERMISSION_HELP)
  )
  .unwrap();
  out
}

fn zig_env_vars() -> String {
  let mut out = String::from(HEADER);
  out.push_str(
    "//! Environment variables documented in `deno --help`, generated from\n\
     //! `libs/cli_parser/src/env_vars.rs`.\n\n\
     pub const EnvVar = struct {\n    name: []const u8,\n    description: []const u8,\n    example: ?[]const u8 = null,\n};\n\n\
     pub const all = [_]EnvVar{\n",
  );
  for v in env_vars::ENV_VARS {
    write!(
      out,
      "    .{{ .name = {}, .description = {}",
      zig_str(v.name),
      zig_str(v.description)
    )
    .unwrap();
    if let Some(e) = v.example {
      write!(out, ", .example = {}", zig_str(e)).unwrap();
    }
    out.push_str(" },\n");
  }
  out.push_str("};\n");
  out
}

/// Render a parse result (or error) in a canonical text form. The Zig port
/// renders the same form, so results can be compared line by line.
fn render_parse(argv: &[String]) -> String {
  let json = |s: &str| serde_json::to_string(s).unwrap();
  let mut out = format!("> {}\n", serde_json::to_string(argv).unwrap());
  match parse::parse(&defs::DENO_ROOT, argv) {
    Ok(r) => {
      if let Some(sub) = &r.subcommand {
        writeln!(out, "subcommand {sub}").unwrap();
      }
      for a in &r.args {
        let values: Vec<String> = a.values.iter().map(|v| json(v)).collect();
        writeln!(
          out,
          "arg {} present={} count={} [{}]",
          a.name,
          a.is_present,
          a.count,
          values.join(",")
        )
        .unwrap();
      }
      if !r.trailing.is_empty() {
        let t: Vec<String> = r.trailing.iter().map(|v| json(v)).collect();
        writeln!(out, "trailing [{}]", t.join(",")).unwrap();
      }
    }
    Err(e) => {
      writeln!(out, "error {:?}: {}", e.kind, json(&e.to_string())).unwrap();
    }
  }
  out
}

/// Find every `svec![...]` made only of string literals.
fn extract_argv(src: &str) -> Vec<Vec<String>> {
  let mut cases = Vec::new();
  let mut rest = src;
  while let Some(start) = rest.find("svec![") {
    rest = &rest[start + "svec![".len()..];
    if let Some((argv, len)) = parse_string_list(rest) {
      cases.push(argv);
      rest = &rest[len..];
    }
  }
  cases
}

/// Parse `"a", r"b", "c"]` and return the strings and the length consumed,
/// or None if the list contains anything but string literals.
fn parse_string_list(src: &str) -> Option<(Vec<String>, usize)> {
  let bytes = src.as_bytes();
  let mut i = 0;
  let mut out = Vec::new();
  loop {
    while i < bytes.len()
      && (bytes[i].is_ascii_whitespace() || bytes[i] == b',')
    {
      i += 1;
    }
    match bytes.get(i)? {
      b']' => return Some((out, i + 1)),
      b'"' => {
        let mut s = String::new();
        i += 1;
        let mut chars = src[i..].char_indices();
        loop {
          let (off, c) = chars.next()?;
          match c {
            '"' => {
              i += off + 1;
              break;
            }
            '\\' => {
              let (_, e) = chars.next()?;
              match e {
                'n' => s.push('\n'),
                'r' => s.push('\r'),
                't' => s.push('\t'),
                '0' => s.push('\0'),
                '\\' | '"' | '\'' => s.push(e),
                // Unicode escapes and line continuations are rare enough in
                // the tests to skip those cases.
                _ => return None,
              }
            }
            c => s.push(c),
          }
        }
        out.push(s);
      }
      b'r' => {
        let hashes = src[i + 1..].bytes().take_while(|b| *b == b'#').count();
        if bytes.get(i + 1 + hashes) != Some(&b'"') {
          return None;
        }
        let body_start = i + 2 + hashes;
        let end = format!("\"{}", "#".repeat(hashes));
        let len = src[body_start..].find(&end)?;
        out.push(src[body_start..body_start + len].to_string());
        i = body_start + len + end.len();
      }
      _ => return None,
    }
  }
}
