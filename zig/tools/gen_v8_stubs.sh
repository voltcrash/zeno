# Regenerates src/v8/rust_symbols.zig from a librusty_v8 archive: every
# symbol the archive expects the Rust side of rusty_v8 (or the temporal_rs
# crate it depends on) to provide.
#
#   tools/gen_v8_stubs.sh path/to/librusty_v8.a
set -euo pipefail
cd "$(dirname "$0")/.."
archive=$1
nm "$archive" 2>/dev/null | awk '$1=="U"{print $2}' | sort -u > /tmp/v8_undef.$$
nm --defined-only "$archive" 2>/dev/null | awk '{print $3}' | sort -u > /tmp/v8_def.$$
syms=$(comm -23 /tmp/v8_undef.$$ /tmp/v8_def.$$ | grep -E '^(v8__|v8_inspector__|crdtp__|cppgc__|rusty_v8_|temporal_rs_)')
rm -f /tmp/v8_undef.$$ /tmp/v8_def.$$
{
  cat <<'HEADER'
// Copyright 2018-2026 the Deno authors. MIT license.
// Generated by zig/tools/gen_v8_stubs.sh. DO NOT EDIT.
//! Symbols that `librusty_v8.a` expects its Rust side to provide: virtual
//! method trampolines for embedder-implemented C++ classes (custom platform,
//! inspector, value serializer, ...) and the `temporal_rs` C API backing
//! V8's Temporal implementation.
//!
//! None of these are implemented yet; each one panics if called. Temporal
//! is disabled at startup (`--no-harmony-temporal`), and the other classes
//! are only used once the port implements them.

fn unimplemented(comptime name: []const u8) noreturn {
    @panic("not implemented in the Zig port: " ++ name);
}

comptime {
HEADER
  for s in $syms; do
    echo "    @export(&struct { fn f() callconv(.c) noreturn { unimplemented(\"$s\"); } }.f, .{ .name = \"$s\" });"
  done
  echo "}"
} > src/v8/rust_symbols.zig
zig fmt src/v8/rust_symbols.zig > /dev/null
